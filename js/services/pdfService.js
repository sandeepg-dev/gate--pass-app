/**
 * Downloads official student pass slip PDF
 * @param {object} pass
 */
function downloadSinglePassPDF(pass) {
  const { jsPDF } = window.jspdf;
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });

  // Outer Institutional Border
  doc.setDrawColor(203, 213, 225);
  doc.setLineWidth(0.8);
  doc.rect(10, 10, 190, 277);

  // Inner accent frame
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.4);
  doc.rect(12, 12, 186, 273);

  // Header Banner
  doc.setFillColor(185, 28, 28);
  doc.rect(10, 10, 190, 26, 'F');

  // Gold accent bar
  doc.setFillColor(234, 179, 8);
  doc.rect(10, 36, 190, 1.2, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text('GRT INSTITUTE OF ENGINEERING AND TECHNOLOGY', 105, 18, { align: 'center' });

  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.text('TIRUTTANI - 631 209 • (AN AUTONOMOUS INSTITUTION) • NAAC A++', 105, 24, { align: 'center' });
  doc.setFont('helvetica', 'bold');
  doc.text('OFFICIAL CAMPUS GATE PASS & AUTHORIZED LEAVE CLEARANCE SLIP', 105, 30, { align: 'center' });

  doc.autoTable({
    startY: 40,
    margin: { left: 14, right: 14 },
    head: [['STUDENT PROFILE', 'OFFICIAL RECORD DETAILS']],
    body: [
      ['Roll Number', pass.rollNo || '-'],
      ['Student Name', pass.name || '-'],
      ['Academic Standing & Sec', formatClassSection(pass.dept, pass.yearSec, pass.academicYear)],
      ['Accommodation Type', /hostel/i.test(pass.accommodation || '') ? 'Hosteller (Resident)' : 'Day Scholar'],
      ['Assigned Counselor', pass.counselorName || '-'],
      ['Verified Parent Phone', pass.parentContact || '-'],
      ['Student Mobile', pass.mobile || '-'],
      ['Applied Timestamp', pass.appliedTime || '-'],
      ['Stated Leave Reason', pass.reason || '-']
    ],
    theme: 'striped',
    headStyles: { fillColor: [30, 41, 59], textColor: [255, 255, 255], fontStyle: 'bold', fontSize: 8 },
    styles: { fontSize: 7.8, cellPadding: 2.5, textColor: [30, 41, 59] }
  });

  const governanceRows = [
    ['Tier 1: Counselor Parent Call Check', pass.counselorApproval?.time || pass.parentCallTime || 'Unverified'],
    ['Tier 2: Class Advisor Endorsement', pass.advisorApproval?.time || 'Pending'],
    ['Tier 3: HOD Authorization', pass.hodApproval?.time || 'Pending'],
    ['Tier 4: Principal Directorate Clearance', pass.principalApproval?.time || pass.approvalTime || 'Pending']
  ];

  if (/hostel/i.test(pass.accommodation || '')) {
    governanceRows.push([
      'Tier 5: Hostel Warden Clearance & Window',
      pass.wardenApproval?.approved
        ? `APPROVED • 20-Min Gate Pass (${pass.validUntil || pass.wardenApproval.time})`
        : 'Pending Warden'
    ]);
  }

  governanceRows.push([
    'Physical Campus Movement Status',
    pass.status === 'Returned' || pass.exitStatus === 'Returned to College'
      ? `RETURNED TO COLLEGE AT ${pass.returnTime} (Exited at ${pass.exitTime})`
      : pass.exitStatus === 'Exited Campus'
      ? `EXITED CAMPUS AT ${pass.exitTime}`
      : 'INSIDE CAMPUS'
  ]);

  doc.autoTable({
    startY: doc.lastAutoTable.finalY + 4,
    margin: { left: 14, right: 14 },
    head: [['GOVERNANCE LEVEL', 'TIMESTAMP SIGN-OFF (IST) & CLEARANCE']],
    body: governanceRows,
    theme: 'grid',
    headStyles: { fillColor: [185, 28, 28], textColor: [255, 255, 255], fontStyle: 'bold', fontSize: 7.5 },
    styles: { fontSize: 7.5, cellPadding: 2.5 }
  });

  const finalY = doc.lastAutoTable.finalY + 16;
  doc.setFontSize(7.5);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(71, 85, 105);

  doc.text('Class Counselor', 24, finalY);
  doc.text('Class Advisor', 72, finalY);
  doc.text('HOD', 122, finalY);
  doc.text('Principal / Security', 158, finalY);

  doc.setDrawColor(148, 163, 184);
  doc.line(20, finalY - 3, 50, finalY - 3);
  doc.line(68, finalY - 3, 98, finalY - 3);
  doc.line(118, finalY - 3, 140, finalY - 3);
  doc.line(155, finalY - 3, 192, finalY - 3);

  doc.save(`GRTIET_Pass_${pass.rollNo}.pdf`);
  showToast(`Gate pass slip PDF downloaded for Roll No: ${pass.rollNo}`, 'success');
}

